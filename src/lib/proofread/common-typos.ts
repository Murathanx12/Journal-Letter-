/**
 * Known English misspellings, and what they are misspellings *of*.
 *
 * WHY A LIST RATHER THAN A DICTIONARY
 *
 * The obvious approach is a spelling dictionary: flag any word it does not
 * know. That was tried, and it is wrong for this product. An English dictionary
 * does not know Turkish either, so it treats every Turkish word as a mistake and
 * offers the nearest English word — turning `askim` into `skim`. Tightening the
 * distance threshold does not save it, because short words in one language sit
 * one edit away from real words in another: `cok` → `cook`, `benim` → `benin`.
 *
 * There is no threshold that separates "a Turkish word" from "an English typo",
 * because the difference is not in the spelling. So the question is inverted:
 * rather than asking "is this word unknown?", which mistrusts every unfamiliar
 * word, this asks "is this a specific, known misspelling?", which mistrusts
 * nothing it has not been told about.
 *
 * The consequence is deliberate. It catches fewer typos than a dictionary
 * would, and in exchange it will never touch a word in another language, a pet
 * name, an invented spelling or a name. Given that the instruction was "if you
 * are not sure, do not even change the spelling", that is the right trade — and
 * the browser's own spell checker is still underlining everything else, in
 * whatever languages the reader has installed, right there in the editor.
 *
 * Adding to this list is safe and welcome: every entry is a word that is simply
 * never correct in English.
 */

