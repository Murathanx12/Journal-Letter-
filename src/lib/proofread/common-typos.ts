/**
 * Entries above ending in `_` are placeholders kept out of the active map:
 * either the "misspelling" is a real word in some contexts (`its`, `lets`,
 * `defiantly`) or the correction is a matter of taste (`favorite`). Correcting
 * those needs to understand the sentence, which this deliberately does not.
 */
const AMBIGUOUS = /_$/;

export const TYPO_CORRECTIONS: ReadonlyMap<string, string> = new Map(
  Object.entries(COMMON_TYPOS).filter(([misspelling]) => !AMBIGUOUS.test(misspelling)),
);

/** The correction for a word, or null if it is not a known misspelling. */
export function correctionFor(word: string): string | null {
  return TYPO_CORRECTIONS.get(word.toLowerCase()) ?? null;
}
